#!/usr/bin/env python3
"""Build the vendored prefix dataset for the internal prefix service.

Merges two sources into src/prefixes/data/prefixes-snapshot.json:

1. The full prefix.cc dump (``/popular/all.file.json``) — the de-facto
   community registry (~3.5k prefixes, ordered by access count, one
   vote-winning namespace per prefix).  No licence is published for the
   prefix.cc data: its API page only asks users to download the whole dump
   and do bulk operations locally, and The Unlicense on its GitHub repository
   covers the site's code, not the data.  The pairs are facts, and the
   operator's own issue https://github.com/cygri/prefix.cc/issues/13 says the
   data is considered public domain (CC0), but that was never published as a
   licence.  The snapshot records exactly this, rather than a licence.
2. The LOV catalog generated by build_lov_catalog.py — contributes
   ``vann:preferredNamespacePrefix`` pairs for vocabularies prefix.cc does
   not know.  LOV data is CC BY 4.0, so the snapshot carries the credit, the
   licence URI and a statement of what was extracted and filtered, as
   CC BY 4.0 §3(a)(1) requires.

Entries are validated against the same constraints the backend enforces
(`[A-Za-z][A-Za-z0-9_-]*` labels ≤ 64 chars, http/https namespaces) so the
Rust loader never has to drop records silently.  On label conflict the
prefix.cc mapping wins (community-voted); the LOV entry is skipped.

The ``sources`` block is the file's provenance and licence record, and the
server reads each source's ``credit`` line into its bulk exports: keep it
accurate when either input changes.

The prefix.cc dump of 2026-06-29 behind the committed snapshot is not stored in
the repository. It can be rebuilt from the snapshot: its pairs are the
``"source": "prefix.cc"`` entries in rank order, plus the one entry this script
drops, ``ontologia`` -> ``http://ub.edu/dades/ontologia/Cinema#Cinemes#`` at
rank 3016 (two '#', so not an IRI).  Rebuilding from that input with
``--prefixcc-snapshot-date 2026-06-29`` and the committed LOV catalogue
reproduces the committed file byte for byte.

Usage:
    python scripts/build_prefix_dataset.py <prefixcc-all.json> <lov-catalog.json.gz> \
        <out.json> [--prefixcc-snapshot-date YYYY-MM-DD]
"""

from __future__ import annotations

import argparse
import gzip
import json
import re
import sys

LABEL_RE = re.compile(r"^[A-Za-z][A-Za-z0-9_-]{0,63}$")

PREFIXCC_URL = "https://prefix.cc/popular/all.file.json"
PREFIXCC_ISSUE = "https://github.com/cygri/prefix.cc/issues/13"
PREFIXCC_MAINTAINER = (
    "Richard Cyganiak; developed at the Digital Enterprise Research Institute (DERI), "
    "National University of Ireland, Galway"
)
PREFIXCC_RIGHTS = (
    "No licence is published for the prefix.cc data. Prefix-to-namespace pairs are facts. "
    "The operator's own issue " + PREFIXCC_ISSUE + " (opened 2014) says all data is "
    "considered public domain (CC0); that has not been published as a licence or dedication."
)
PREFIXCC_CODE_LICENSE = (
    "The Unlicense (https://github.com/cygri/prefix.cc/blob/master/LICENSE.txt), "
    "covering the prefix.cc site's source code, not its data."
)

LOV_LICENSE = "CC BY 4.0"
LOV_LICENSE_URL = "https://creativecommons.org/licenses/by/4.0/"
LOV_ATTRIBUTION = (
    "Linked Open Vocabularies (LOV), https://lov.linkeddata.es/, created by "
    "Pierre-Yves Vandenbussche and Bernard Vatant, hosted by the Ontology Engineering "
    "Group, Universidad Politécnica de Madrid"
)


# Characters an IRI may not contain (RFC 3987), and a second '#': an IRI has
# at most one fragment, so `…/Cinema#Cinemes#` is not an IRI and would make the
# Turtle and SPARQL exports unparseable.
IRI_FORBIDDEN_RE = re.compile(r'[\x00-\x20<>"{}|\\^`]')


def valid_namespace(ns: str) -> bool:
    return (
        isinstance(ns, str)
        and ns.startswith(("http://", "https://"))
        and len(ns) <= 500
        and ns.count("#") <= 1
        and not IRI_FORBIDDEN_RE.search(ns)
    )


def sources_block(
    pcc_date: str, pcc_kept: int, pcc_dropped: int, lov_source: dict, lov_stats: dict
) -> dict:
    """The provenance and licence record for both sources.

    Everything that varies with the inputs is computed, so a rebuild from the
    same inputs reproduces the committed block exactly.
    """
    lov_date = lov_source["snapshot_date"]
    lov_modified = (
        f"Extracted and filtered: the prefix and namespace LOV records for each vocabulary "
        f"in its dump of {lov_date}; of {lov_stats['vocabularies']} vocabularies, "
        f"{lov_stats['bound_by_prefixcc']} whose label prefix.cc already binds and "
        f"{lov_stats['invalid']} with an invalid label or namespace were left out, "
        f"leaving {lov_stats['added']}; ranked after the prefix.cc entries and re-encoded as JSON."
    )
    return {
        "prefix.cc": {
            "name": "prefix.cc",
            "homepage": "https://prefix.cc/",
            "url": PREFIXCC_URL,
            "snapshot_date": pcc_date,
            "entries": pcc_kept,
            "maintainer": PREFIXCC_MAINTAINER,
            "license": None,
            "rights": PREFIXCC_RIGHTS,
            "code_license": PREFIXCC_CODE_LICENSE,
            "modifications": (
                f"Entries with an invalid label or namespace dropped ({pcc_dropped} in this "
                "snapshot); prefix.cc's popularity order kept as rank; a source field added."
            ),
            "credit": (
                f"prefix.cc (https://prefix.cc/), maintained by Richard Cyganiak, developed at "
                f"DERI, NUI Galway; snapshot of {pcc_date}. No licence is published for this "
                f"data; its operator has stated it is considered public domain (CC0): "
                f"{PREFIXCC_ISSUE}"
            ),
        },
        "lov": {
            "name": "Linked Open Vocabularies (LOV)",
            "homepage": "https://lov.linkeddata.es/",
            "url": lov_source["url"],
            "snapshot_date": lov_date,
            "entries": lov_stats["added"],
            "license": LOV_LICENSE,
            "license_url": LOV_LICENSE_URL,
            "attribution": LOV_ATTRIBUTION,
            "modifications": lov_modified,
            "credit": (
                f"{LOV_ATTRIBUTION}; {LOV_LICENSE} ({LOV_LICENSE_URL}). Modified: "
                f"{lov_stats['added']} prefix/namespace pairs extracted from the LOV dump of "
                f"{lov_date}, keeping only valid pairs whose label prefix.cc does not already bind."
            ),
        },
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("prefixcc")
    ap.add_argument("lov_catalog")
    ap.add_argument("out")
    ap.add_argument("--prefixcc-snapshot-date", default="unknown")
    args = ap.parse_args()

    # dict order == prefix.cc popularity order (dump is sorted by access count)
    pcc = json.load(open(args.prefixcc, encoding="utf-8"))
    lov = json.load(gzip.open(args.lov_catalog))

    entries = []
    seen = {}
    dropped = 0
    for rank, (label, ns) in enumerate(pcc.items(), start=1):
        if not LABEL_RE.match(label) or not valid_namespace(ns):
            dropped += 1
            continue
        seen[label] = ns
        entries.append({"prefix": label, "namespace": ns, "rank": rank, "source": "prefix.cc"})

    lov_added = 0
    lov_bound = 0
    lov_invalid = 0
    for vocab in lov["vocabularies"]:
        label, ns = vocab["prefix"], vocab["nsp"]
        if label in seen:
            lov_bound += 1
            continue
        if not LABEL_RE.match(label) or not valid_namespace(ns):
            lov_invalid += 1
            continue
        lov_added += 1
        entries.append(
            {
                "prefix": label,
                "namespace": ns,
                "rank": len(pcc) + lov_added,
                "source": "lov",
            }
        )

    out = {
        "format_version": 1,
        "sources": sources_block(
            args.prefixcc_snapshot_date,
            len(pcc) - dropped,
            dropped,
            lov["source"],
            {
                "vocabularies": len(lov["vocabularies"]),
                "bound_by_prefixcc": lov_bound,
                "invalid": lov_invalid,
                "added": lov_added,
            },
        ),
        "prefixes": entries,
    }
    json.dump(out, open(args.out, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(f"prefix.cc entries: {len(pcc)} (dropped {dropped} invalid), lov additions: {lov_added}")
    print(f"total: {len(entries)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
